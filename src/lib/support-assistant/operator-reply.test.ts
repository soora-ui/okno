import { describe, expect, it } from "vitest";
import { hasInventedDetails } from "@/lib/support-assistant/operator-reply";

// Сторож стоит между живым оператором и мастером. Модель причёсывает ответ,
// не понимая предметной части — иначе человека бы не звали. Всё, что она
// может дописать сверх текста оператора, для мастера выглядит инструкцией от
// поддержки, поэтому такие ответы отправляются дословно.

describe("hasInventedDetails", () => {
  it("ловит дописанный путь по интерфейсу", () => {
    expect(
      hasInventedDetails(
        "нет, автопродление не отключится, пока не кончится оплаченный период",
        "Автопродление не отключится до конца периода. Отключить — Настройки → Аккаунт → Подписка.",
      ),
    ).toBe(true);
  });

  it("ловит дописанный срок", () => {
    expect(
      hasInventedDetails(
        "вернём деньги, напиши на почту",
        "Вернём деньги в течение 5 рабочих дней — напиши на почту.",
      ),
    ).toBe(true);
  });

  it("ловит дописанное название кнопки", () => {
    expect(
      hasInventedDetails(
        "пусть отвяжет карту в настройках",
        "Отвяжи карту в настройках кнопкой «Отключить и отвязать карту».",
      ),
    ).toBe(true);
  });

  it("пропускает причёсывание без новых фактов", () => {
    expect(
      hasInventedDetails(
        "не, так низя, тариф меняется только с нового периода",
        "Так нельзя: тариф меняется только с нового периода.",
      ),
    ).toBe(false);
  });

  it("пропускает вычищенную внутреннюю кухню", () => {
    expect(
      hasInventedDetails(
        "щас гляну в базе... ага, у него платёж висит в pending, скоро пройдёт",
        "Платёж ещё обрабатывается, скоро пройдёт.",
      ),
    ).toBe(false);
  });

  it("не считает отсебятиной цифру самого оператора", () => {
    expect(hasInventedDetails("3 дня максимум", "Максимум 3 дня.")).toBe(false);
  });

  it("не считает отсебятиной кавычки, которые были у оператора", () => {
    expect(
      hasInventedDetails(
        'жми «Подключить ЮKassa» там же',
        'Нажми «Подключить ЮKassa» в том же блоке.',
      ),
    ).toBe(false);
  });
});
