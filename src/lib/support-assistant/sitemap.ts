const topicsById = new Map(SUPPORT_SITEMAP.map((topic) => [topic.id, topic]));

export function getSupportTopic(id: string): SupportTopic | undefined {
  return topicsById.get(id);
}

function normalizeTitle(value: string) {
  return value.toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ").trim();
}

const topicsByTitle = new Map(
  SUPPORT_SITEMAP.map((topic) => [normalizeTitle(topic.title), topic]),
);

/**
 * Поиск темы по названию. Модель ссылается на источники именно названиями, а
 * не id: id — латиница и внутренняя кухня, и если такой ответ утечёт в чат,
 * пользователь увидит «prepayment» вместо человеческого текста. Название же
 * утечь не страшно — это обычные русские слова.
 */
export function getSupportTopicByTitle(title: string): SupportTopic | undefined {
  return topicsByTitle.get(normalizeTitle(title));
}

/**
 * Компактная строка индекса — уходит в промпт по каждой теме без исключения.
 * Формат намеренно скупой: название + путь, этого хватает, чтобы бот знал о
 * существовании фичи и мог назвать точный путь даже без подробностей.
 */
export function renderTopicIndexLine(topic: SupportTopic): string {
  return `${topic.title} — ${topic.path}`;
}

/** Подробный блок темы — попадает в промпт только для релевантных тем. */
export function renderTopicDetails(topic: SupportTopic): string {
  const lines = [`### ${topic.title}`, `Путь: ${topic.path}`, topic.answer];

  if (topic.steps?.length) {
    lines.push("Шаги:", ...topic.steps.map((step, index) => `${index + 1}. ${step}`));
  }

  if (topic.notes?.length) {
    lines.push("Нюансы:", ...topic.notes.map((note) => `- ${note}`));
  }

  return lines.join("\n");
}
