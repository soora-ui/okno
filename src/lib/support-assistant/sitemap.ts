// Карта сервиса okno.business для AI-поддержки: где что лежит в кабинете,
// как включается и какие у фичи ограничения.
//
// Зачем отдельный модуль, а не плоский список фактов: бот обязан отвечать
// «где нажать», а не «такой функции, кажется, нет». Поэтому каждая тема
// несёт точный путь по интерфейсу, готовый короткий ответ и нюансы. Индекс
// всех тем (id + название + путь) уходит в промпт ЦЕЛИКОМ и всегда — так бот
// физически не может сказать «функции нет», если она есть. Подробности
// подмешиваются только по релевантным темам, чтобы не жечь токены.
//
// Это НЕ база знаний AI-консультанта для клиентов мастера (та собирается из
// мануалов по услугам, см. src/lib/service-manuals.ts) — не путать.
//
// ВАЖНО: при изменении фич/цен/лимитов обновляй этот файл — он единственный
// источник знаний поддержки.

export type SupportTopic = {
  /** Стабильный идентификатор, на него ссылается `related`. */
  id: string;
  /** Название темы для индекса и заголовка блока. */
  title: string;
  /** Точный путь по интерфейсу: «Настройки → Запись → Параметры записи». */
  path: string;
  /**
   * Слова-зацепки в нижнем регистре, БЕЗ окончаний («предоплат», а не
   * «предоплата») — поиск матчит по вхождению подстроки, это дешёвая замена
   * морфологии для русского.
   */
  keywords: string[];
  /** Готовый ответ на 1–2 предложения: его можно отдать почти дословно. */
  answer: string;
  /** Пошаговая инструкция, если тема требует нескольких кликов. */
  steps?: string[];
  /** Ограничения, зависимости и подводные камни. */
  notes?: string[];
  /** id смежных тем — подмешиваются в промпт вместе с этой. */
  related?: string[];
};

