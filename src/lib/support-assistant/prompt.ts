// Системный промпт AI-поддержки сервиса okno.business — чат для владельцев
// аккаунтов/мастеров по вопросам использования сервиса. Это ОТДЕЛЬНАЯ фича от
// AI-консультанта, который отвечает клиентам мастера по услугам (тот работает
// по мануалам услуг, см. src/lib/service-manuals.ts) — не переиспользовать.
//
// Тон задан по образцу банковской поддержки: короткий конкретный ответ, точный
// путь по интерфейсу, без воды и без предложений «помочь с чем-то ещё».
//
// Три запрета стоят отдельно, потому что каждый из них ломает доверие
// по-своему:
//   • отправлять «в поддержку» — пользователь уже в ней, это замкнутый круг;
//   • гадать словами «возможно / наверное» — поддержка либо знает, либо зовёт
//     человека, третьего не дано;
//   • рассказывать про своё устройство — карта, инструкция, стек, хранилище.
//     Пользователю нужен ответ, а не экскурсия по внутренностям.
//
// Про устройство важно отдельно: модель знает про веб-разработку и хостинг из
// общих знаний и охотно ответит «где хранятся данные» или «есть ли API», даже
// если в базе про это ни слова. Такой ответ будет либо правдой (утечка), либо
// выдумкой (хуже) — поэтому тема закрыта целиком.

export type SupportPromptContext = {
  /**
   * Залогинен ли собеседник. От этого зависит развилка «нет ответа»: мастера
   * можно передать живому оператору, анонима — некому.
   */
  isAuthenticated: boolean;
  /**
   * Последняя реплика живого специалиста, если разговор с ним ещё открыт.
   * Появляется в промпте, чтобы бот мог отличить ответ на встречный вопрос
   * оператора от нового вопроса к себе.
   */
  openEscalationReply?: string | null;
  /**
   * Предыдущие реплики разговора для поиска по базе: без них уточняющий
   * вопрос не находит тему, о которой шла речь.
   */
  retrievalContext?: string;
};

/**
 * Системный промпт из двух частей ради кэша Anthropic. Кэш — совпадение
 * префикса: любой изменившийся байт обнуляет всё после него. Поэтому сначала
 * идёт то, что одинаково для всех запросов до следующего деплоя (правила и
 * индекс всех тем), с отметкой кэша, а после неё — то, что меняется от
 * запроса к запросу (вход в аккаунт, разговор со специалистом, подробности
 * тем под вопрос). Приветствие из промпта убрано совсем: его ставит код
 * (greeting.ts), иначе флаг «первое сообщение за день» ломал бы кэш.
 */
export type SupportSystemPrompt = {
  stable: string;
  dynamic: string;
};

// Текст специалиста идёт в промпт внутри тега. Угловые скобки в нём
// заменяем, чтобы закрывающий тег из текста не вывел остаток наружу —
// причёсанный ответ оператора собирается из реплик, где был и текст мастера.
function escapePromptTag(text: string): string {
  return text.replace(/</g, "‹").replace(/>/g, "›");
}

