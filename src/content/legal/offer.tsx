// Таблица тарифов собирается из src/config/plans.ts — того же источника, из
// которого цены берёт витрина и биллинг. Цена в договоре и цена в платеже
// расходиться не должны.
function OfferPlanTable() {
  return (
    <div className="overflow-x-auto rounded-panel border border-line">
      <table className="w-full min-w-[32rem] border-collapse text-left text-sm">
        <thead>
          <tr style={{ backgroundColor: "var(--color-panel)" }}>
            <th className="px-4 py-3 font-medium text-ink">Тариф</th>
            <th className="px-4 py-3 font-medium text-ink">Состав</th>
            <th className="px-4 py-3 font-medium text-ink whitespace-nowrap">
              Стоимость
            </th>
          </tr>
        </thead>
        <tbody>
          {pricingPlans.map((plan, index) => (
            <tr key={plan.id} className={index > 0 ? "border-t border-line" : ""}>
              <td className="px-4 py-3 align-top font-medium text-ink">
                {plan.title}
              </td>
              <td className="px-4 py-3 align-top leading-6 text-ink-soft">
                {plan.description}
              </td>
              <td className="px-4 py-3 align-top whitespace-nowrap text-ink-soft">
                {formatPlanPrice(plan.priceRub)} {plan.period}
              </td>
            </tr>
          ))}
          <tr className="border-t border-line">
            <td className="px-4 py-3 align-top font-medium text-ink">
              Доплата за сотрудника
            </td>
            <td className="px-4 py-3 align-top leading-6 text-ink-soft">
              За каждого активного сотрудника рабочего пространства сверх
              включённых в тариф «Студия и барбершоп»
            </td>
            <td className="px-4 py-3 align-top whitespace-nowrap text-ink-soft">
              {formatPlanPrice(extraSeatPriceRub)} в месяц
            </td>
          </tr>
        </tbody>
      </table>
    </div>
  );
}

