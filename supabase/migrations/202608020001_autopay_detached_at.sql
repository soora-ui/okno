-- Когда привязка карты закончилась: мастер нажал «Отключить и отвязать» либо
-- мы сами сдались после неудачных списаний.
--
-- Без этой отметки нельзя отличить «карта не привязалась при оплате» от
-- «карта была и её сняли»: и там и там последний платёж помечен autopay=true,
-- а строки в subscription_payment_methods нет (она удаляется, а не
-- архивируется). Из-за этого настройки показывали мастеру «автопродление не
-- включилось» сразу после того, как он сам его выключил.

alter table profiles
  add column if not exists autopay_detached_at timestamptz;

-- Существующим профилям отметку не проставляем: у них привязок и не было,
-- null здесь читается как «привязка не заканчивалась».

-- Откат:
-- alter table profiles drop column if exists autopay_detached_at;
