-- Подписки на уведомления в магазине мастера (okno-tz-yookassa-oauth.md).
--
-- Предоплата и сертификаты создаются OAuth-токеном мастера и живут в его
-- магазине — значит и уведомление payment.succeeded ЮKassa шлёт по адресу,
-- привязанному к этому токену, а не по тому, что настроен в кабинете
-- платформы для её собственного shopId. Без явной подписки вебхук
-- okno.business не получает по таким платежам ничего: клиент платит, запись
-- остаётся в pending_payment, и джоба /api/jobs/prepayments через 15 минут
-- снимает бронь — деньги списаны, записи нет.
--
-- Храним выданные ЮKassa id подписок в виде
-- [{"id": "wh-...", "event": "payment.succeeded"}]: они нужны, чтобы при
-- переподключении не плодить дубли и чтобы снять подписки при отключении
-- магазина мастером.
alter table master_yookassa_accounts
  add column if not exists webhooks jsonb not null default '[]'::jsonb;
